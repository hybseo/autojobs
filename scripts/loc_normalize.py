def _hits(v):
    """이 글자에서 읽히는 시·도를 전부 모읍니다."""
    got = []
    low = v.lower()
    for w in SEOUL_WORDS:
        if w in v:
            got.append("서울")
    for w, sido in AREA_WORDS:
        if w in v:
            got.append(sido)
    for pat, sido in ROMAN:
        if re.search(pat, low):
            got.append(sido)
    out = []
    for g in got:
        if g not in out:
            out.append(g)
    return out


def normalize_location(loc):
    """근무지 한 칸을 시·도 표기로 맞춥니다. 못 정하면 빈 문자열입니다."""
    v = re.sub(r"\s+", " ", str(loc or "")).strip()
    if not v:
        return UNSET

    # 이미 시·도로 시작하면 그대로 둡니다. 여기서 손대지 않습니다.
    if v.startswith(SIDO):
        return v

    if OVERSEAS.search(v):
        return "해외"
    # 통째로 애매한 말일 때만 비웁니다 (「본사」·「Korea」·「3 Locations」).
    if AMBIGUOUS.fullmatch(v):
        return UNSET

    got = _hits(v)
    # 「경기」와 「경기 평택」이 같이 걸리면 좁은 쪽만 남깁니다
    # (KOR-Gyeonggi-do-Pyeongtaek-KLA 가 둘 다 걸립니다).
    got = [g for g in got if not any(o != g and o.startswith(g) for o in got)]
    if len(got) == 1:
        return got[0]
    if len(got) > 1:
        # 여러 곳이 읽히면 — 같은 시·도 안이면 그 시·도로, 아니면 비웁니다.
        # 「천안/아산사업장」 → 충남,  「송도/서울」 → 추측하지 않고 빈칸
        heads = {g.split()[0] for g in got}
        return heads.pop() if len(heads) == 1 else UNSET

    # 시설 이름뿐이면 비웁니다 (「전동화공장」·「연구소」).
    if PLACE_WORD.search(v):
        return UNSET

    # 남은 것은 회사명·브랜드명입니다.
    return UNSET
